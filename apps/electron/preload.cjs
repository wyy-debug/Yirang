const { contextBridge, ipcRenderer, webUtils } = require('electron');
const bootstrap = ipcRenderer.invoke('desktop:bootstrap');
void bootstrap.catch(() => {});
const invoke = (channel, ...args) => bootstrap.then(() => ipcRenderer.invoke(channel, ...args));
contextBridge.exposeInMainWorld('desktop', {
  filePath: (file) => (webUtils?.getPathForFile ? webUtils.getPathForFile(file) : file.path || ''),
  workManagement: (args) => invoke('desktop:work-management', args),
  lightApps: (payload) => invoke('desktop:light-apps', payload),
  language: (value) => invoke('desktop:language', value),
  startup: (stage) => ipcRenderer.invoke('desktop:startup', stage),
  tool: (name, args) => invoke('desktop:tool', name, args),
  threads: () => invoke('desktop:threads'),
  aiTools: (action, payload) => invoke('desktop:ai-tools', action, payload),
  voice: (action, payload) => invoke('desktop:voice', action, payload),
  chat: (action, payload) => invoke('desktop:chat', action, payload),
  projects: (action, payload) => invoke('desktop:projects', action, payload),
  permissions: (action, payload) => invoke('desktop:permissions', action, payload),
  conversation: (action, payload) => invoke('desktop:conversation', action, payload),
  nativeWork: (workspaceId) => invoke('desktop:native-work', workspaceId),
  inventory: (refresh) => invoke('desktop:inventory', refresh),
  search: (action, payload) => invoke('desktop:search', action, payload),
  closeResult: (id, error) => invoke('desktop:close-result', id, error),
  files: (action, payload) => invoke('desktop:files', action, payload),
  python: (action, payload) => invoke('desktop:python', action, payload),
  review: (action, payload) => invoke('desktop:review', action, payload),
  app: (action, payload) => invoke('desktop:app', action, payload),
  reconnect: () => invoke('desktop:reconnect'),
  draftPresence: (id, present) => invoke('desktop:draft-presence', id, present),
  switchThread: (id) => invoke('desktop:switch-thread', id),
  send: (text) => invoke('desktop:send', text),
  sendBlocks: (blocks) => invoke('desktop:send-blocks', blocks),
  workflowDelivery: (payload) => invoke('desktop:workflow-delivery', payload),
  stop: (threadId) => invoke('desktop:stop', threadId),
  steer: (threadId, text) => invoke('desktop:steer', { threadId, text }),
  respond: (id, response) => invoke('desktop:respond', id, response),
  composerImages: (action, payload) => invoke('desktop:composer-images', action, payload),
  attach: (blocks) => invoke('desktop:attach', blocks),
  messageAttachments: (payload) => invoke('desktop:message-attachments', payload),
  openLink: (url) => invoke('desktop:open-link', url),
  image: (path) => invoke('desktop:image', path),
  browser: (action, payload) => invoke('desktop:browser', action, payload),
  browserApproval: (id, accepted) => invoke('desktop:browser-approval', id, accepted),
  canvasContext: (value) => invoke('desktop:canvas-context', value),
  workspaceOpenResult: (value) => invoke('desktop:workspace-open-result', value),
  captureCanvas: (bounds) => invoke('desktop:canvas-capture', bounds),
  outputs: (action, id, objectId) => invoke('desktop:outputs', action, id, objectId),
  onEvent: (callback) => ipcRenderer.on('desktop:event', (_event, value) => callback(value)),
});
