import { build } from 'esbuild';
import { mkdir, readFile, writeFile, readdir, unlink } from 'node:fs/promises';
import { resolve, relative, isAbsolute } from 'node:path';
import { pathToFileURL } from 'node:url';

// Writes the two panel HTML files from an in-memory esbuild result; used by both one-shot builds and watch rebuilds.
async function writePanel(outputFiles) {
  const script = outputFiles
    .find((f) => f.path.endsWith('.js'))
    .text.replace(/<\/script/gi, '<\\/script');
  const style = outputFiles.find((f) => f.path.endsWith('.css'))?.text ?? '';
  const electronStyle = await readFile('apps/panel/electron-mode.css', 'utf8');
  const panelHtml = `<!doctype html><html lang="zh-CN"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>一壤 · Yirang</title><style>${style}</style></head><body><div id="root"></div><script>${script}</script></body></html>`;
  await writeFile('dist/panel.html', panelHtml);
  await writeFile(
    'dist/panel-electron.html',
    panelHtml
      .replace('<html lang="zh-CN">', '<html class="electron-mode" lang="zh-CN">')
      .replace('</style>', `${electronStyle}</style>`)
      .replaceAll('Codex 原消息框', 'Codex 对话')
      .replaceAll('Codex 原对话', 'Codex 对话')
      .replaceAll('原消息框', 'Codex 对话')
      .replaceAll('原对话', 'Codex 对话')
      .replaceAll('原会话', '当前对话'),
  );
}
const panelWriter = {
  name: 'panel-html',
  setup(b) {
    b.onEnd(async (result) => {
      if (!result.errors.length && result.outputFiles) await writePanel(result.outputFiles);
    });
  },
};

// Every esbuild step of the desktop build; scripts/dev-electron.mjs runs the same list in watch mode.
export async function buildSteps() {
  const { version } = JSON.parse(await readFile('package.json', 'utf8'));
  await writeFile(
    'packages/contracts/version.ts',
    `// Generated by scripts/build.mjs from the package version.\nexport const DESKTOP_VERSION = ${JSON.stringify(version)};\n`,
  );
  await mkdir('dist', { recursive: true });
  const electronEntries = (await readdir('apps/electron', { recursive: true }))
    .filter((file) => file.endsWith('.mjs'))
    .sort()
    .map((file) => `apps/electron/${file}`);
  // Directory moves must not leave obsolete modules in the next installer.
  const outputDirectory = resolve('dist/electron');
  await mkdir(outputDirectory, { recursive: true });
  const expectedModules = new Set(
    electronEntries.map((file) => resolve(outputDirectory, file.slice('apps/electron/'.length))),
  );
  for (const file of await readdir(outputDirectory, { recursive: true })) {
    if (!file.endsWith('.mjs')) continue;
    const target = resolve(outputDirectory, file);
    const withinOutput = relative(outputDirectory, target);
    if (withinOutput.startsWith('..') || isAbsolute(withinOutput)) {
      throw new Error(`Build output escaped its directory: ${file}`);
    }
    if (!expectedModules.has(target)) await unlink(target);
  }
  return [
    {
      entryPoints: ['packages/local-runtime/work/completion-worker.ts'],
      outfile: 'dist/completion-worker.mjs', bundle: true, platform: 'node', format: 'esm', target: 'node24',
    },
    {
      entryPoints: electronEntries,
      outdir: 'dist/electron',
      outbase: 'apps/electron',
      outExtension: { '.js': '.mjs' },
      bundle: false,
      platform: 'node',
      format: 'esm',
      target: 'node24',
    },
    {
      entryPoints: ['apps/electron/remote/remote-app-server.mjs'],
      outfile: 'dist/yirang-service.mjs',
      bundle: true,
      platform: 'node',
      format: 'esm',
      target: 'node24',
      banner: {
        js: 'import { createRequire as __serviceRequire } from "node:module"; const require = __serviceRequire(import.meta.url);',
      },
    },
    {
      entryPoints: ['packages/mcp-adapter/server.ts'],
      outfile: 'dist/server.mjs',
      bundle: true,
      platform: 'node',
      format: 'esm',
      target: 'node24',
      banner: {
        js: 'import { createRequire as __aiDesktopBannerRequire } from "node:module"; const require = __aiDesktopBannerRequire(import.meta.url);',
      },
    },
    {
      entryPoints: ['apps/electron/shell.js'],
      outfile: 'dist/shell.js',
      bundle: true,
      platform: 'browser',
      format: 'iife',
      target: 'es2022',
    },
    {
      entryPoints: ['packages/local-runtime/files/generated-sync-worker.ts'],
      outfile: 'dist/generated-sync-worker.mjs',
      bundle: true,
      platform: 'node',
      format: 'esm',
      target: 'node24',
    },
    {
      entryPoints: ['packages/local-runtime/retrieval/retrieval-worker.ts'],
      outfile: 'dist/retrieval-worker.mjs',
      bundle: true,
      platform: 'node',
      format: 'esm',
      target: 'node24',
      external: ['sqlite-vec'],
      banner: {
        js: 'import { createRequire } from "node:module"; const require = createRequire(import.meta.url);',
      },
    },
    {
      entryPoints: ['apps/panel/index.tsx'],
      bundle: true,
      write: false,
      platform: 'browser',
      format: 'iife',
      target: 'es2022',
      minify: true,
      outfile: 'panel.js',
      loader: { '.svg': 'dataurl', '.png': 'dataurl' },
      plugins: [panelWriter],
    },
  ];
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const step of await buildSteps()) await build(step);
  console.log('Built local stdio server and self-contained MCP App.');
}
